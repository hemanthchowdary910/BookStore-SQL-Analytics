-- QUERY 19 : LIST THE CITIES WHERE CUSTOMERS WHO SPENT OVER $30 ARE LOCATED

SELECT
	C.CITY,
	COUNT(*) AS LIST_CITIES
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE
	O.TOTAL_AMOUNT > 30
