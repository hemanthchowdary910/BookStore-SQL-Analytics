-- QUERY 26 : RANK CUSTOMERS BASED ON THEIR TOTAL SPENDING

SELECT
	C.CUSTOMER_ID,
	C.NAME,
	SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT,
	RANK() OVER(
		ORDER BY SUM(O.TOTAL_AMOUNT) DESC
	) AS CUSTOMER_RANK
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON O.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY
	C.CUSTOMER_ID,
	C.NAME;


-- QUERY 27 : DENSE RANK BOOKS BASED ON TOTAL REVENUE GENERATED

SELECT
	B.BOOK_ID,
	B.TITLE,
	SUM(O.TOTAL_AMOUNT) AS TOTAL_REVENUE,
	DENSE_RANK() OVER(
		ORDER BY SUM(O.TOTAL_AMOUNT) DESC
	) AS BOOK_RANK
FROM
	ORDERS O
	JOIN BOOKS B
		ON O.BOOK_ID = B.BOOK_ID
GROUP BY
	B.BOOK_ID,
	B.TITLE;


-- QUERY 28 : CALCULATE THE RUNNING TOTAL OF REVENUE

SELECT
	ORDER_DATE,
	SUM(TOTAL_AMOUNT) AS DAILY_REVENUE,
	SUM(SUM(TOTAL_AMOUNT)) OVER(
		ORDER BY ORDER_DATE
	) AS RUNNING_REVENUE
FROM
	ORDERS
GROUP BY
	ORDER_DATE
ORDER BY
	ORDER_DATE;


-- QUERY 29 : SHOW THE PREVIOUS ORDER AMOUNT FOR EACH CUSTOMER

SELECT
	C.CUSTOMER_ID,
	C.NAME,
	O.ORDER_DATE,
	O.TOTAL_AMOUNT,
	LAG(O.TOTAL_AMOUNT) OVER(
		PARTITION BY C.CUSTOMER_ID
		ORDER BY O.ORDER_DATE
	) AS PREVIOUS_ORDER_AMOUNT
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON O.CUSTOMER_ID = C.CUSTOMER_ID;


-- QUERY 30 : FIND THE HIGHEST REVENUE GENERATING BOOK FROM EACH GENRE

WITH BOOK_REVENUE AS (

	SELECT
		B.GENRE,
		B.TITLE,
		SUM(O.TOTAL_AMOUNT) AS TOTAL_REVENUE,

		ROW_NUMBER() OVER(
			PARTITION BY B.GENRE
			ORDER BY SUM(O.TOTAL_AMOUNT) DESC
		) AS RN

	FROM
		ORDERS O
		JOIN BOOKS B
			ON O.BOOK_ID = B.BOOK_ID

	GROUP BY
		B.GENRE,
		B.TITLE

)

SELECT
	GENRE,
	TITLE,
	TOTAL_REVENUE
FROM
	BOOK_REVENUE
WHERE
	RN = 1;
