-- QUERY 13 : FIND THE AVERAGE PRICE OF BOOKS IN THE FANTASY GENRE

SELECT
	AVG(PRICE) AS AVERAGE_PRICE
FROM
	BOOKS
WHERE
	GENRE = 'Fantasy';


-- QUERY 14 : LIST CUSTOMERS WHO HAVE PLACED AT LEAST 2 ORDERS

SELECT
	C.CUSTOMER_ID,
	C.NAME,
	COUNT(O.ORDER_ID) AS ORDER_COUNT
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
	C.CUSTOMER_ID,
	C.NAME
HAVING
	COUNT(O.ORDER_ID) >= 2
ORDER BY
	ORDER_COUNT ASC;


-- QUERY 15 : FIND THE MOST FREQUENTLY ORDERED BOOK WITH CUSTOMER NAMES

SELECT
	C.NAME,
	B.TITLE,
	O.BOOK_ID,
	COUNT(O.ORDER_ID) AS ORDER_COUNT
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON O.CUSTOMER_ID = C.CUSTOMER_ID
	JOIN BOOKS B
		ON O.BOOK_ID = B.BOOK_ID
GROUP BY
	O.BOOK_ID,
	B.TITLE,
	C.NAME
ORDER BY
	ORDER_COUNT DESC;


-- QUERY 16 : FIND THE MOST FREQUENTLY ORDERED BOOK

