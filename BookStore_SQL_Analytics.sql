	C.CITY;


-- QUERY 20 : FIND THE CUSTOMER WHO SPENT THE MOST ON ORDERS

SELECT
	C.NAME,
	C.CUSTOMER_ID,
	SUM(O.TOTAL_AMOUNT) AS TOTAL_SPENT
FROM
	ORDERS O
	JOIN CUSTOMERS C
		ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY
	C.CUSTOMER_ID,
	C.NAME
ORDER BY
	TOTAL_SPENT DESC
LIMIT
	1;


-- QUERY 21 : CALCULATE THE STOCK REMAINING AFTER FULFILLING ALL ORDERS

SELECT
	B.BOOK_ID,
	B.TITLE,
	B.STOCK,
	COALESCE(SUM(O.QUANTITY), 0) AS ORDER_QUANTITY,
	B.STOCK - COALESCE(SUM(O.QUANTITY), 0) AS REMAINING_QUANTITY
FROM
	BOOKS B
	LEFT JOIN ORDERS O
		ON B.BOOK_ID = O.BOOK_ID
GROUP BY
	B.BOOK_ID,
	B.TITLE,
	B.STOCK
ORDER BY
	B.BOOK_ID;
